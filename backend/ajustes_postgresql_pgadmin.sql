-- 1. Ampliar el campo 'rut' a varchar(12) para soportar RUT con puntos y guion (ej: 12.345.678-9)
ALTER TABLE public.usuario 
ALTER COLUMN rut TYPE character varying(12);

-- 2. Eliminar la columna redundante 'password_hash' (Django utiliza de forma nativa la columna 'password')
ALTER TABLE public.usuario 
DROP COLUMN IF EXISTS password_hash;

-- 3. Nueva tabla para Denominadores y Población Objetivo (Requerimiento MINSAL / Evaluación)
CREATE TABLE IF NOT EXISTS public.param_manager_poblacionanual (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    anio smallint NOT NULL,
    poblacion_total numeric(12, 2) NOT NULL DEFAULT 28500.00,
    mujeres_20_64 numeric(12, 2) NOT NULL DEFAULT 5226.00,
    hombres_20_64 numeric(12, 2) NOT NULL DEFAULT 4800.00,
    adultos_mayores_65 numeric(12, 2) NOT NULL DEFAULT 3200.00,
    mujeres_25_64_pap numeric(12, 2) NOT NULL DEFAULT 5393.00,
    ninos_12_23_meses numeric(12, 2) NOT NULL DEFAULT 350.00,
    adolescentes_10_19 numeric(12, 2) NOT NULL DEFAULT 2100.00,
    prevalencia_dm2 numeric(12, 2) NOT NULL DEFAULT 2280.00,
    prevalencia_hta numeric(12, 2) NOT NULL DEFAULT 4200.00,
    ninos_menores_3_caries numeric(12, 2) NOT NULL DEFAULT 480.00,
    actualizado_en timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT param_manager_poblacionanual_pkey PRIMARY KEY (id),
    CONSTRAINT param_manager_poblacionanual_anio_key UNIQUE (anio),
    CONSTRAINT param_manager_poblacionanual_anio_check CHECK (anio >= 0)
);

